#!/usr/bin/env python3
"""A saved world's region files as hashes (phase 2, P2-4): what the chunk scenes compare, small enough to publish.

usage: regiondump.py WORLD OUT.json [--base BASE.json]

For every region file of every chunk store under WORLD (each dimension's region/, entities/ and poi/ directories):
  - the header: for each of the 1024 slots, its sector offset, sector count and timestamp (where each chunk sits in the
    file and when it was written: these follow write order and the wall clock, not the chunk's data);
  - each stored chunk: its compression type, the sha256 of the bytes as stored (length, type and compressed body: what
    "byte for byte" means for one chunk), and the sha256 of its decompressed NBT;
  - with --base: for each chunk whose decompressed NBT differs from the base world's (the chunks the scene saved), the
    sha256 of each top-level NBT key's decoded value, so a difference can be named (LastUpdate, InhabitedTime,
    sections, ...) without keeping the world; and the chunks that aren't in the base world at all (generated by the
    scene: must be none).
Hashes and counts only (no game data): the dump is published on the ci-logs branch.
"""
import hashlib
import importlib.util
import json
import os
import struct
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location("worlddiff", os.path.join(HERE, "worlddiff.py"))
wd = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(wd)

STORES = ("region", "entities", "poi")


def sha(b):
    return hashlib.sha256(b).hexdigest()[:24]


def region_file(path):
    """(header, chunks): header {slot: [offset, count, timestamp]}, chunks {"cx,cz": {"comp", "stored", "raw"}}."""
    with open(path, "rb") as f:
        data = f.read()
    header, chunks = {}, {}
    if len(data) < 8192:
        return header, chunks, len(data)
    base = os.path.basename(path).split(".")
    rx, rz = int(base[1]), int(base[2])
    decoded = wd.region_chunks(path)
    for idx in range(1024):
        loc = struct.unpack(">I", data[idx * 4:idx * 4 + 4])[0]
        ts = struct.unpack(">I", data[4096 + idx * 4:4096 + idx * 4 + 4])[0]
        off, count = loc >> 8, loc & 0xFF
        if off == 0 and count == 0:
            continue
        header[idx] = [off, count, ts]
        cx, cz = rx * 32 + (idx & 31), rz * 32 + (idx >> 5)
        start = off * 4096
        entry = {}
        if start + 5 <= len(data):
            length = struct.unpack(">I", data[start:start + 4])[0]
            entry["comp"] = data[start + 4]
            entry["stored"] = sha(data[start:start + 4 + length])
        comp, raw, err = decoded.get((cx, cz), (None, None, "not decoded"))
        if raw is not None:
            entry["raw"] = sha(raw)
        if err:
            entry["error"] = err
        chunks["%d,%d" % (cx, cz)] = entry
    return header, chunks, len(data)


def key_hashes(raw):
    try:
        nbt = wd.read_nbt(raw)
    except Exception as e:  # noqa: BLE001 - reported, not fatal
        return {"(unreadable)": str(e)}
    return {k: sha(json.dumps(wd.canon(v), sort_keys=True).encode()) for k, v in nbt.items()}


def dump(world, base=None):
    out = {"stores": {}}
    raw_of = {}
    for dim_key, dim_dir in sorted(wd.dimensions(world).items()):
        for store in STORES:
            d = os.path.join(dim_dir, store)
            if not os.path.isdir(d):
                continue
            key = os.path.relpath(d, world)
            files, chunks = {}, {}
            for name in sorted(os.listdir(d)):
                if not name.endswith(".mca"):
                    continue
                header, ch, size = region_file(os.path.join(d, name))
                files[name] = {"size": size, "header": header}
                chunks.update(ch)
            out["stores"][key] = {"files": files, "chunks": chunks}
            if base is not None:
                bchunks = base.get("stores", {}).get(key, {}).get("chunks", {})
                changed, new = {}, []
                decoded = None
                for pos, e in sorted(chunks.items()):
                    b = bchunks.get(pos)
                    if b is None:
                        new.append(pos)
                    if b is not None and b.get("raw") == e.get("raw"):
                        continue
                    if decoded is None:
                        decoded = wd.store_chunks(d)
                    cx, cz = (int(v) for v in pos.split(","))
                    raw = decoded.get((cx, cz), (None, None, None))[1]
                    changed[pos] = key_hashes(raw) if raw is not None else {"(undecodable)": e.get("error", "?")}
                out["stores"][key]["changed"] = changed
                out["stores"][key]["notInBase"] = new
    return out


def main(argv):
    if len(argv) < 2:
        print(__doc__)
        return 2
    base = None
    if "--base" in argv:
        i = argv.index("--base")
        with open(argv[i + 1]) as f:
            base = json.load(f)
        argv = argv[:i] + argv[i + 2:]
    res = dump(argv[0], base)
    with open(argv[1], "w") as f:
        json.dump(res, f, separators=(",", ":"))
    n = sum(len(s["chunks"]) for s in res["stores"].values())
    c = sum(len(s.get("changed", {})) for s in res["stores"].values())
    print("%s: %d stored chunks in %d stores, %d differ from the base" % (argv[0], n, len(res["stores"]), c))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
