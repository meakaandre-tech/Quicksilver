#!/usr/bin/env python3
"""The chunk scenes' report (phase 2, P2-4; ci/server/chunks-run.sh): server-thread chunk loading and saving, tick
spikes, and the saved files, vanilla against Quicksilver on one runner.

usage: compare-chunks.py RESULTS_DIR REPORT_DIR

Reads RESULTS_DIR/<suite>-chunks/<scene>/<side><round>/ (ci-harness-result.json, jfr.json, dump.json) and
RESULTS_DIR/<suite>-chunks/base.json. For each scene:
  - time: per round, the harness's tick numbers (average, p99, max, ticks over 50 ms, the slowest ticks; the autosave
    and save-all ticks) and the JFR summary's server-thread ms per tick in chunk loading, saving and autosave (in the
    tick and between ticks); the median of each side, and the median of the per-round ratios (Quicksilver / the
    vanilla run of the same round: the runner drifts between rounds, a pair shares the drift);
  - the saved files (dump.json): every stored chunk of every store (region, entities, poi) compared with vanilla round
    1's: present on both sides, the same bytes as stored ("byte for byte"), the same decompressed data, and for a
    difference the top-level keys that differ; region headers (where each chunk sits in its file, and its timestamp)
    apart, since they follow write order and the clock. Vanilla's own rounds 2-N against round 1 are its noise: a
    Quicksilver difference on a chunk where vanilla's rounds all agree is Quicksilver's;
  - no chunk generated by a scene (every saved chunk was in the saved terrain).
Gates (GATES below; while MEASURING is true, everything is reported and nothing fails).
Writes REPORT_DIR/chunks.md and REPORT_DIR/chunks.json; exit 1 on a gated failure.
"""
import glob
import re
import json
import os
import statistics
import sys

MEASURING = False
# the scenes whose saved files are gated exactly (vanilla's own rounds match there): Quicksilver's saved chunks must be
# vanilla's. The fly-over's saves follow chunk unload timing (which tick each chunk is saved in: vanilla's own rounds
# differ in about a thousand chunks' LastUpdate and pending ticks), so its files are reported, not gated. Entity files are
# reported only (entities move between saves in vanilla's own rounds too)
EXACT_FILES = ("save", "churn")


def load(path):
    try:
        with open(path) as f:
            return json.load(f)
    except (OSError, ValueError):
        return None


def med(xs):
    xs = [x for x in xs if x is not None]
    return statistics.median(xs) if xs else None


def fmt(v, nd=3):
    if v is None:
        return "-"
    if isinstance(v, float):
        return ("%." + str(nd) + "f") % v
    return str(v)


def rounds_of(scene_dir):
    out = {}
    for d in sorted(glob.glob(os.path.join(scene_dir, "*"))):
        name = os.path.basename(d)
        for side in ("vanilla", "quicksilver"):
            if name.startswith(side) and name[len(side):].isdigit():
                out[(side, int(name[len(side):]))] = d
    return out


def numbers(d):
    r = load(os.path.join(d, "ci-harness-result.json")) or {}
    j = load(os.path.join(d, "jfr.json")) or {}
    autos = [a for a in r.get("autosaves", []) if a.get("stage") == "RUNNING"]
    return {
        "finished": "msptAvg" in r and not r.get("error"),
        "error": r.get("error"),
        "msptAvg": r.get("msptAvg"), "msptP99": r.get("msptP99"), "msptMax": r.get("msptMax"),
        "over50": r.get("ticksOver50ms"),
        "slow": r.get("slowTicks", [])[:8],
        "autosaveTicks": [a.get("tick") for a in autos],
        "loadAll": (j.get("load") or {}).get("msPerTickAll"), "loadInTick": (j.get("load") or {}).get("msPerTickInTick"),
        "saveAll": (j.get("save") or {}).get("msPerTickAll"), "saveInTick": (j.get("save") or {}).get("msPerTickInTick"),
        "autosaveAll": (j.get("autosave") or {}).get("msPerTickAll"),
        "chunks": r.get("chunks"),
        "jfr": j,
    }


CHUNKS_ON = "Quicksilver chunks:"
CHUNKS_FALLBACK = "Quicksilver chunks fallback:"
# a chunk the game could not read or write (vanilla's log lines for it)
READ_ERRORS = re.compile(r"Couldn't load chunk|Failed to read chunk|Failed to load chunk|is corrupt|Chunk file at .* is in the wrong location|Failed to store chunk|Couldn't save chunk|Recovering corrupted")


def text(path):
    try:
        with open(path, errors="replace") as f:
            return f.read()
    except OSError:
        return ""


def status_check(d, side, where, fails, verify=False):
    """A run's Chunks module status: fully on (and verify on, for a verify run) with Quicksilver, absent without; no fallback."""
    log = text(os.path.join(d, "server.log"))
    st = re.findall(re.escape(CHUNKS_ON) + r" (.*)", log)
    if side == "quicksilver":
        if not st:
            fails.append("%s: no '%s' status line" % (where, CHUNKS_ON))
        elif any(re.search(r"=(off|fallback)|^off", x) for x in st):
            fails.append("%s: Chunks module not fully on: %s" % (where, [x for x in st if re.search(r"=(off|fallback)|^off", x)][0][:300]))
        elif verify and not any("verify=on" in x for x in st):
            fails.append("%s: verify mode not on" % where)
    elif st:
        fails.append("%s: a Chunks status line without Quicksilver" % where)
    fb = [l for l in log.splitlines() if CHUNKS_FALLBACK in l]
    if fb:
        fails.append("%s: %d Chunks fallbacks (first: %s)" % (where, len(fb), fb[0][:400]))
    err = [l for l in log.splitlines() if READ_ERRORS.search(l)]
    if err:
        fails.append("%s: %d chunk read or write errors (first: %s)" % (where, len(err), err[0][:300]))
    return st[-1] if st else None


def autosave_ms(d, n):
    """The tick time of each autosave tick (the game's own), from ticks.json."""
    t = load(os.path.join(d, "ticks.json")) or []
    return [t[k] for k in n["autosaveTicks"] if 0 <= k < len(t)]


def store_compare(a, b):
    """Chunk-by-chunk comparison of two dumps (b against a)."""
    res = {}
    for key in sorted(set(a["stores"]) | set(b["stores"])):
        sa, sb = a["stores"].get(key, {}), b["stores"].get(key, {})
        ca, cb = sa.get("chunks", {}), sb.get("chunks", {})
        only_a = sorted(set(ca) - set(cb))
        only_b = sorted(set(cb) - set(ca))
        stored_diff, raw_diff, keys = [], [], {}
        for pos in sorted(set(ca) & set(cb)):
            ea, eb = ca[pos], cb[pos]
            if ea.get("raw") != eb.get("raw"):
                raw_diff.append(pos)
                ka = sa.get("changed", {}).get(pos, {})
                kb = sb.get("changed", {}).get(pos, {})
                for k in sorted(set(ka) | set(kb)):
                    if ka.get(k) != kb.get(k):
                        keys[k] = keys.get(k, 0) + 1
            elif ea.get("stored") != eb.get("stored"):
                stored_diff.append(pos)
        # headers: slots whose offset/count or timestamp differ
        ha = {(f, s): v for f, x in sa.get("files", {}).items() for s, v in x.get("header", {}).items()}
        hb = {(f, s): v for f, x in sb.get("files", {}).items() for s, v in x.get("header", {}).items()}
        place = sum(1 for k in set(ha) & set(hb) if ha[k][:2] != hb[k][:2])
        stamp = sum(1 for k in set(ha) & set(hb) if ha[k][2] != hb[k][2])
        res[key] = {"chunks": len(cb), "onlyVanilla": only_a, "onlyQuicksilver": only_b, "rawDiff": raw_diff,
                    "storedDiffSameRaw": stored_diff, "keys": keys, "headerPlaceDiff": place, "headerTimeDiff": stamp,
                    "notInBase": sb.get("notInBase", [])}
    return res


def kill_check(sdir, lines, out, fails):
    """The kill check (chunks-run.sh): each killed save holds, per chunk, either the saved terrain's data or the complete
    save's (never a broken chunk or a third version), and the killed world loads again; Quicksilver as vanilla."""
    suite = os.path.basename(sdir)[:-len("-chunks")]
    kd = os.path.join(sdir, "kill")
    if not os.path.isdir(kd):
        return
    base = load(os.path.join(sdir, "base.json"))
    lines.append("## %s / kill: a kill -9 mid-save (save-all flush of 625 changed chunks)\n" % suite)
    lines.append("| run | killed mid-save | chunks: complete save's / saved terrain's / other / unreadable (region) | entities, poi: other / unreadable | reloaded |")
    lines.append("|---|---|---|---|---|")
    res = {}
    for d in sorted(glob.glob(os.path.join(kd, "*-killed*"))):
        name = os.path.basename(d)
        side, r = name.split("-killed")
        where = "%s/kill %s" % (suite, name)
        complete = load(os.path.join(kd, "%s-complete%s" % (side, r), "dump.json"))
        killed = load(os.path.join(d, "dump.json"))
        log = text(os.path.join(d, "server.log"))
        mid = os.path.exists(os.path.join(d, "kill.txt")) and "CI HARNESS CMD t=100 " not in log
        status_check(os.path.join(kd, "%s-complete%s" % (side, r)), side, where + " (complete)", fails)
        rd = os.path.join(kd, "%s-reload%s" % (side, r))
        reloaded = "CI HARNESS RUN DONE" in text(os.path.join(rd, "server.log"))
        status_check(rd, side, where + " (reload)", fails)
        if not reloaded:
            fails.append("%s: the killed world did not load and run again" % where)
        if not (complete and killed and base):
            fails.append("%s: a dump is missing" % where)
            continue
        counts, other_stores = {}, []
        for key, sk in killed["stores"].items():
            sc = complete["stores"].get(key, {}).get("chunks", {})
            sb = base["stores"].get(key, {}).get("chunks", {})
            c = {"complete": 0, "base": 0, "other": [], "unreadable": []}
            for pos, e in sk["chunks"].items():
                if "error" in e or "raw" not in e:
                    c["unreadable"].append(pos)
                elif pos in sc and e.get("raw") == sc[pos].get("raw"):
                    c["complete"] += 1
                elif pos in sb and e.get("raw") == sb[pos].get("raw"):
                    c["base"] += 1
                else:
                    c["other"].append(pos)
            counts[key] = c
            if c["unreadable"]:
                fails.append("%s: %d unreadable chunks in %s (first %s)" % (where, len(c["unreadable"]), key, c["unreadable"][0]))
            if c["other"] and key.endswith("region"):
                fails.append("%s: %d chunks in %s hold neither the saved terrain's data nor the complete save's (first %s)" % (
                    where, len(c["other"]), key, c["other"][0]))
        reg = next((c for k, c in counts.items() if k.endswith("region")), {"complete": 0, "base": 0, "other": [], "unreadable": []})
        rest = [(k.split("/")[-1], c) for k, c in sorted(counts.items()) if not k.endswith("region")]
        lines.append("| %s | %s | %d / %d / %d / %d | %s | %s |" % (
            name, "yes" if mid else "**no** (finished first)", reg["complete"], reg["base"], len(reg["other"]), len(reg["unreadable"]),
            "; ".join("%s %d / %d" % (k, len(c["other"]), len(c["unreadable"])) for k, c in rest) or "-",
            "yes" if reloaded else "**no**"))
        res[name] = {"mid": mid, "region": {k: (v if isinstance(v, int) else len(v)) for k, v in reg.items()}}
    lines.append("\nEach chunk of a killed save is either the complete save's or the saved terrain's: a kill loses the chunks"
                 " not yet written, and breaks none. Entity and POI files are reported only (their data follows entity and"
                 " POI timing, as in vanilla's own rounds).\n")
    out["%s/kill" % suite] = res


def main(results, report_dir):
    os.makedirs(report_dir, exist_ok=True)
    lines, out, fails = [], {}, []
    lines.append("# Chunk scenes (P2-4)\n")
    if MEASURING:
        lines.append("Measuring: everything below is reported, nothing is gated yet.\n")
    suites = sorted(glob.glob(os.path.join(results, "*-chunks")))
    if not suites:
        lines.append("No chunk scene results.\n")
    for sdir in suites:
        suite = os.path.basename(sdir)[:-len("-chunks")]
        base = load(os.path.join(sdir, "base.json"))
        for scene_dir in sorted(d for d in glob.glob(os.path.join(sdir, "*")) if os.path.isdir(d) and d != os.path.join(sdir, "base")):
            scene = os.path.basename(scene_dir)
            rs = rounds_of(scene_dir)
            if not rs:
                continue
            nums = {k: numbers(v) for k, v in rs.items()}
            n_rounds = sorted({r for _, r in rs})
            lines.append("## %s / %s\n" % (suite, scene))
            lines.append("| round | side | finished | mspt avg | p99 | max | over 50 ms | load ms/tick (in tick) | save ms/tick (in tick) | autosave ms/tick | autosave ticks (ms) | slowest ticks |")
            lines.append("|---|---|---|---|---|---|---|---|---|---|---|---|")
            for r in n_rounds:
                for side in ("vanilla", "quicksilver"):
                    n = nums.get((side, r))
                    if not n:
                        lines.append("| %d | %s | missing |" % (r, side))
                        fails.append("%s/%s: %s round %d missing" % (suite, scene, side, r))
                        continue
                    am = autosave_ms(rs[(side, r)], n)
                    lines.append("| %d | %s | %s | %s | %s | %s | %s | %s (%s) | %s (%s) | %s | %s | %s |" % (
                        r, side, "yes" if n["finished"] else "**no** %s" % (n["error"] or ""), fmt(n["msptAvg"]),
                        fmt(n["msptP99"]), fmt(n["msptMax"]), fmt(n["over50"]), fmt(n["loadAll"]), fmt(n["loadInTick"]),
                        fmt(n["saveAll"]), fmt(n["saveInTick"]), fmt(n["autosaveAll"]),
                        ", ".join("%s (%s)" % (k, fmt(m, 1)) for k, m in zip(n["autosaveTicks"], am)) or "-",
                        ", ".join("%d: %s" % (s["tick"], fmt(s["ms"], 1)) for s in n["slow"][:5])))
                    if not n["finished"]:
                        fails.append("%s/%s: %s round %d did not finish" % (suite, scene, side, r))
                    status_check(rs[(side, r)], side, "%s/%s %s round %d" % (suite, scene, side, r), fails)
            lines.append("")
            # medians and per-round ratios
            summary = {}
            lines.append("| measure | vanilla median | Quicksilver median | Quicksilver / vanilla, median of rounds (range) |")
            lines.append("|---|---|---|---|")
            for m, label in (("msptAvg", "MSPT average"), ("msptP99", "MSPT p99"), ("msptMax", "slowest tick (ms)"),
                             ("over50", "ticks over 50 ms"), ("loadAll", "chunk load, ms per tick (server thread)"),
                             ("loadInTick", "  of it in the tick"), ("saveAll", "chunk save, ms per tick (server thread)"),
                             ("saveInTick", "  of it in the tick"), ("autosaveAll", "autosave, ms per tick")):
                v = [nums[("vanilla", r)][m] for r in n_rounds if ("vanilla", r) in nums]
                q = [nums[("quicksilver", r)][m] for r in n_rounds if ("quicksilver", r) in nums]
                ratios = []
                for r in n_rounds:
                    a = nums.get(("vanilla", r), {}).get(m)
                    b = nums.get(("quicksilver", r), {}).get(m)
                    if a and b is not None:
                        ratios.append(b / a)
                summary[m] = {"vanilla": med(v), "quicksilver": med(q), "ratio": med(ratios),
                              "ratioMin": min(ratios) if ratios else None, "ratioMax": max(ratios) if ratios else None}
                lines.append("| %s | %s | %s | %s (%s to %s) |" % (label, fmt(med(v)), fmt(med(q)), fmt(med(ratios)),
                                                                   fmt(summary[m]["ratioMin"], 2), fmt(summary[m]["ratioMax"], 2)))
            lines.append("")
            # where the server thread's chunk time goes (round 1 of each side)
            for side in ("vanilla", "quicksilver"):
                n = nums.get((side, 1))
                if not n or not n["jfr"]:
                    continue
                j = n["jfr"]
                lines.append("<details><summary>%s round 1: server thread by phase (samples, about 1 ms each; window %s ms, %s samples outside, %s untimed)</summary>\n" % (
                    side, j.get("windowMs"), j.get("samplesOutsideWindow"), j.get("samplesUntimed")))
                lines.append("| phase | in tick (Java / native) | between ticks (Java / native) | ms per tick, all | allocated MB |")
                lines.append("|---|---|---|---|---|")
                for p in j.get("phases", []):
                    lines.append("| %s | %d / %d | %d / %d | %s | %s |" % (p["phase"], p["tickJava"], p["tickNative"], p["betweenJava"],
                                                                     p["betweenNative"], fmt(p["msPerTickAll"]), fmt(p["allocMB"], 1)))
                lines.append("\nTop chunk methods (inclusive): " + ", ".join("%s %d" % (x["method"], x["samples"]) for x in j.get("inclusive", [])[:60]))
                lines.append("\nTop chunk methods (self): " + ", ".join("%s %d" % (x["method"], x["samples"]) for x in j.get("self", [])[:30]))
                lines.append("\nThreads (all samples in the window): " + ", ".join("%s %d" % (x["thread"], x["samples"]) for x in j.get("threads", [])))
                lines.append("\n</details>\n")
            # inside loads and saves, all rounds of each side summed (JFR anchors: an anchor's direct callees)
            agg = {}
            for (side, r), n in nums.items():
                for a, v in (n["jfr"].get("anchors") or {}).items():
                    acc = agg.setdefault(side, {}).setdefault(a, [0, {}, {}])
                    acc[0] += v["samples"]
                    for c in v["callees"]:
                        acc[1][c["method"]] = acc[1].get(c["method"], 0) + c["samples"]
                    for c in v.get("callees2", []):
                        acc[2][c["path"]] = acc[2].get(c["path"], 0) + c["samples"]
            for side in ("vanilla", "quicksilver"):
                if side not in agg:
                    continue
                lines.append("<details><summary>%s, all rounds: inside loads and saves (samples under each method, its callees)</summary>\n" % side)
                for a, (n_a, c1, c2) in sorted(agg[side].items(), key=lambda kv: -kv[1][0]):
                    top = sorted(c1.items(), key=lambda kv: -kv[1])[:12]
                    top2 = sorted(c2.items(), key=lambda kv: -kv[1])[:12]
                    lines.append("- **%s** %d: %s<br>two down: %s" % (a, n_a, ", ".join("%s %d" % kv for kv in top),
                                                                     ", ".join("%s %d" % kv for kv in top2)))
                lines.append("\n</details>\n")
            # saved files
            dumps = {k: load(os.path.join(v, "dump.json")) for k, v in rs.items()}
            ref = dumps.get(("vanilla", 1))
            files = {}
            if ref:
                noise = {}
                for r in n_rounds:
                    if r == 1 or not dumps.get(("vanilla", r)):
                        continue
                    for key, c in store_compare(ref, dumps[("vanilla", r)]).items():
                        nz = noise.setdefault(key, {"raw": set(), "stored": set(), "only": set(), "keys": {}})
                        nz["raw"].update(c["rawDiff"])
                        nz["stored"].update(c["storedDiffSameRaw"])
                        nz["only"].update(c["onlyVanilla"] + c["onlyQuicksilver"])
                        for k, v in c["keys"].items():
                            nz["keys"][k] = nz["keys"].get(k, 0) + v
                lines.append("Saved files against vanilla round 1 (every stored chunk; vanilla's rounds 2-%d are its noise):\n" % max(n_rounds))
                lines.append("| round | side | store | chunks | only one side | data differs (outside vanilla's noise) | same data, other bytes | keys that differ | header: place / time differs | not in the saved terrain |")
                lines.append("|---|---|---|---|---|---|---|---|---|---|")
                for r in n_rounds:
                    for side in ("vanilla", "quicksilver"):
                        if (side, r) == ("vanilla", 1) or not dumps.get((side, r)):
                            continue
                        for key, c in store_compare(ref, dumps[(side, r)]).items():
                            nz = noise.get(key, {"raw": set(), "stored": set(), "only": set()})
                            only = c["onlyVanilla"] + c["onlyQuicksilver"]
                            raw_out = [p for p in c["rawDiff"] if p not in nz["raw"]]
                            stored_out = [p for p in c["storedDiffSameRaw"] if p not in nz["stored"] and p not in nz["raw"]]
                            only_out = [p for p in only if p not in nz["only"]]
                            if side == "quicksilver" and scene in EXACT_FILES and not key.endswith("entities") and (raw_out or stored_out or only_out):
                                fails.append("%s/%s: Quicksilver round %d, %s: %d chunks' data differ from vanilla's (outside vanilla's own"
                                             " noise), %d stored bytes only, %d on one side only; keys %s" % (
                                                 suite, scene, r, key, len(raw_out), len(stored_out), len(only_out),
                                                 ", ".join("%s %d" % kv for kv in sorted(c["keys"].items())) or "-"))
                            files.setdefault(side, []).append({"round": r, "store": key, "rawOut": len(raw_out), "storedOut": len(stored_out),
                                                                "onlyOut": len(only_out), "notInBase": len(c["notInBase"])})
                            lines.append("| %d | %s | %s | %d | %d (%d) | %d (%d) | %d (%d) | %s | %d / %d | %d |" % (
                                r, side, key, c["chunks"], len(only), len(only_out), len(c["rawDiff"]), len(raw_out),
                                len(c["storedDiffSameRaw"]), len(stored_out),
                                ", ".join("%s %d" % kv for kv in sorted(c["keys"].items())) or "-",
                                c["headerPlaceDiff"], c["headerTimeDiff"], len(c["notInBase"])))
                            if c["notInBase"] and key.endswith("region"):
                                fails.append("%s/%s: %s round %d generated %d chunks in %s" % (suite, scene, side, r, len(c["notInBase"]), key))
                lines.append("")
                lines.append("Vanilla's noise (rounds 2-%d against 1): %s\n" % (max(n_rounds), "; ".join(
                    "%s: %d data, %d bytes only, %d one side, keys %s" % (k, len(v["raw"]), len(v["stored"]), len(v["only"]),
                                                                           ", ".join("%s %d" % kv for kv in sorted(v["keys"].items())) or "-")
                    for k, v in sorted(noise.items()))))
            # the full runs' verify run: finished, verify on, no fallback, its saved files as vanilla's
            vd = os.path.join(scene_dir, "quicksilver-verify")
            if os.path.isdir(vd):
                vn = numbers(vd)
                st = status_check(vd, "quicksilver", "%s/%s verify run" % (suite, scene), fails, verify=True)
                if not vn["finished"]:
                    fails.append("%s/%s verify run: did not finish" % (suite, scene))
                vdump = load(os.path.join(vd, "dump.json"))
                vdiff = "-"
                if vdump and ref:
                    cs = store_compare(ref, vdump)
                    vdiff = ", ".join("%s: %d data, %d bytes only" % (k.split("/")[-1], len(c["rawDiff"]), len(c["storedDiffSameRaw"])) for k, c in cs.items())
                lines.append("Verify run (full runs: chunks verify mode, every shared section checked against a real copy): %s; %s; saved files against vanilla round 1: %s\n" % (
                    "finished" if vn["finished"] else "**did not finish**", (st or "no status line")[:200], vdiff))
            elif os.environ.get("CI_MODE") == "full" and scene != "kill":
                fails.append("%s/%s: no verify run in a full run" % (suite, scene))
            out["%s/%s" % (suite, scene)] = {"summary": summary, "files": files}
    for sdir in suites:
        kill_check(sdir, lines, out, fails)
    if fails:
        lines.append("## Failures%s\n" % (" (reported: measuring)" if MEASURING else ""))
        lines += ["- " + f for f in fails]
    with open(os.path.join(report_dir, "chunks.md"), "w") as f:
        f.write("\n".join(lines) + "\n")
    with open(os.path.join(report_dir, "chunks.json"), "w") as f:
        json.dump({"scenes": out, "failures": fails}, f, indent=1)
    print("\n".join(lines[:4]))
    return 1 if fails and not MEASURING else 0


if __name__ == "__main__":
    if len(sys.argv) != 3:
        print(__doc__)
        sys.exit(2)
    sys.exit(main(sys.argv[1], sys.argv[2]))
